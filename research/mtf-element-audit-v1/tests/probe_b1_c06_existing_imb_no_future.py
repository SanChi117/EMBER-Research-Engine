#!/usr/bin/env python3
"""B1/C06 independent Binance USD-M source-known IMB prefix experiment.

Unlike B1/C05's quarantined toy POI, this zone is generated by unchanged
course-v05 confirmed_imb from 3 CLOSED candles only (no next-bar lookahead).
It remains just a classic wick-gap candidate, not fully course-approved POI.
"""
from pathlib import Path
import sys,csv,io,json,zipfile
from decimal import Decimal
ROOT=Path(__file__).resolve().parents[1]
for p in (ROOT/"tools",ROOT/"tests",ROOT/"d05",ROOT.parent/"mtf-course-v05"/"src"):
    sys.path.insert(0,str(p))
from verify_d04_full_manifest_c08 import checked_download
from strict_vision_d04 import verify_raw_zip
from c08_source_bound_poi_b1 import _locked_receipt
from course_primitives_v05 import Bar
from source_imb_prefix_b1 import observe_source_defined_imbs

URL="https://data.binance.vision/data/futures/um/daily/klines/BTCUSDT/15m/BTCUSDT-15m-2026-10-01.zip"
def main(output=None):
    rec,_=_locked_receipt("BTCUSDT","15m",1790812800000,ROOT/"evidence"/"c08")
    assert rec["url"]==URL
    zipbytes=checked_download(URL,25_000_000,40)
    checksum=checked_download(URL+".CHECKSUM",1024,40)
    checked=verify_raw_zip(URL,zipbytes,checksum)
    assert checked["zip_sha256"]==rec["zip_sha256"] and checked["raw_csv_sha256"]==rec["raw_csv_sha256"]
    with zipfile.ZipFile(io.BytesIO(zipbytes)) as archive:
        with archive.open("BTCUSDT-15m-2026-10-01.csv") as handle:
            rows=list(csv.reader(io.TextIOWrapper(handle,encoding="utf-8-sig",newline="")))
    if rows[0][0].lower()=="open_time":rows=rows[1:]
    assert len(rows)==96
    bars=[Bar(int(r[0]),int(r[6])+1,*(float(Decimal(r[i])) for i in (1,2,3,4)),"15m") for r in rows]
    assert all(a.end==b.start for a,b in zip(bars,bars[1:]))
    result=observe_source_defined_imbs(bars,bars[-1].end)
    assert result,"NO_CLASSIC_IMB_FOUND_IN_THIS_ARCHIVE__CANNOT_CLAIM_SOURCE_TEST"
    first=result[0]
    idx=next(i for i,b in enumerate(bars) if b.end==first.known_at_ms)
    original=observe_source_defined_imbs(bars[:idx+1],first.known_at_ms)
    assert original and original[0].imbalance_id==first.imbalance_id
    assert first.known_at_ms==bars[idx].end and idx>=2
    assert first.readiness=="NOT_TRADE_READY"
    assert first.status=="CLASSIC_WICK_GAP_SOURCE_CANDIDATE_NOT_ACADEMIC_POI_SIGNOFF"
    report={
       "cycle":"B1_C06_NO_HINDSIGHT_SOURCE_IMB_PREFIX",
       "archive_url":URL,
       "archive_rows":96,
       "source_zip_sha256":checked["zip_sha256"],
       "source_raw_csv_sha256":checked["raw_csv_sha256"],
       "source_kind":"EXISTING_V05_CLASSIC_THREE_CLOSED_CANDLE_WICK_GAP",
       "total_source_imb_candidates":len(result),
       "first_source_id":first.imbalance_id,
       "first_source_side":first.side,
       "first_source_known_at_ms":first.known_at_ms,
       "first_source_exists_at_its_own_known_at":True,
       "first_source_future_data_used":False,
       "first_source_post_known_contact_at_ms":first.contact.first_contact_at_ms if first.contact else None,
       "source_bar_contiguous":True,
       "valid_academic_parent_poi":False,
       "academic_reaction_approved":False,
       "order_ready":False,
       "status":"SOURCE_DEFINED_CANDIDATE_PREFIX_OBSERVATION_ONLY"
    }
    print(json.dumps(report,ensure_ascii=False,sort_keys=True,indent=2))
    if output:Path(output).write_text(json.dumps(report,sort_keys=True,indent=2)+"\n",encoding="utf8")
    return 0
if __name__=="__main__":
    raise SystemExit(main(sys.argv[1] if len(sys.argv)>1 else None))
